#include "zf_time.h"
#include "zf_timer.h"
#include "zf_task.h"
#include "zf_critical.h"
#include "stdlib.h"

/* 全局系统 tick。 */
uint32_t ZF_tick = 0;

/******************************************************************************
 * 功能  获取系统 tick
******************************************************************************/
uint32_t ZF_getSystemTick(void)
{
    return ZF_tick;
}

/******************************************************************************
 * 功能  获取系统时间(ms)
******************************************************************************/
uint32_t ZF_getSystemTimeMS(void)
{
    return ZF_tick * ZF_TICK_PERIOD;
}

/******************************************************************************
 * 功能  延时指定 tick
 * 说明  如果任务系统已运行，则当前任务进入延时状态并触发调度；
 *       否则退化为忙等。
******************************************************************************/
void ZF_delayTick(uint32_t tick)
{
    /* 有任务系统时，优先使用让出 CPU 的方式延时。 */
    if (TASK_IS_SYSTEM_RUN() && TASK_IS_SCHEDULE_ON())
    {
        /* 保存并恢复中断上下文的局部变量。 */
        ZF_SR_VAL();
        
        /* 进入临界区，保护当前任务状态更新。 */
        ZF_CRITICAL_ENTER();
        
        /* 当前任务进入延时态。 */
        Task_delay(pCurrentTask, tick);
        
        /* 退出临界区。 */
        ZF_CRITICAL_EXIT();
        
        /* 立即重新调度，让其他任务运行。 */
        Task_schedule();
    }
    /* 没有任务系统时只能忙等。 */
    else
    {
        uint32_t startTick = ZF_getSystemTick();
        while((ZF_getSystemTick() - startTick) < tick);
    }
}

/******************************************************************************
 * 功能  系统 tick 中断钩子
 * 说明  这是时间子系统的枢纽：
 *       1. 递增全局 tick。
 *       2. 驱动软件定时器。
 *       3. 更新任务延时与运行时间。
 *       4. 触发调度。
******************************************************************************/
void ZF_timeTick (void)
{
    /* 系统 tick 自增。 */
    ZF_tick++;
    
    /* 驱动软件定时器。 */
    Timer_process();
    
    /* 更新任务延时。 */
    Task_timeUpdate();
    
    /* tick 到来后重新判断是否需要切换任务。 */
    Task_schedule();
}

